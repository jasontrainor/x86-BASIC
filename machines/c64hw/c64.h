#ifndef C64_H
#define C64_H

/*
 * The hardware of the BASIC V2 machine (the 1982 64KB home computer), as
 * BASIC programs see it, shared by its BASIC (machines/c64/). It is a
 * model of memory and the chips' registers - what PEEK and POKE reach -
 * and of the firmware's screen editor, not an emulation of the 6502 or
 * of any ROM: nothing of any ROM is here.
 *
 *   memory.c   64KB of RAM; the I/O chips at $D000-$DFFF; the processor
 *              port at 0-1, which banks the character "ROM" (this
 *              project's characters) in at $D000. The BASIC and KERNAL
 *              ROMs read as 0.
 *   vic.c      the picture, drawn from memory as the VIC-II draws it:
 *              text, its colours, the border, and the registers
 *   sid.c      the sound chip: its voices and envelopes, on the PC speaker
 *   screen.c   the screen editor: printing (PETSCII, with its control
 *              characters), the cursor, logical lines, scrolling, and
 *              reading a line off the screen when Return is pressed
 *   keys.c     the keyboard: PC keys as the machine's keys, the key
 *              buffer, the jiffy clock and time passing (c64_tick)
 *   chars.c    the two character sets (generated by tools/mkc64chars.py)
 *
 * The firmware keeps its state where programs PEEK and POKE it, and this
 * model keeps it there too (the C64_ addresses below).
 */

// The firmware's variables, at their addresses.
enum {
    C64_PORT_DDR = 0, C64_PORT = 1,           // the processor port (banking)
    C64_TXTTAB = 43, C64_VARTAB = 45, C64_MEMSIZ = 55,   // BASIC's pointers
    C64_STATUS = 144,                         // ST
    C64_JIFFY = 160,                          // 160-162: the clock, 60 a second
    C64_LSTX = 197,                           // the key down (matrix code; 64 none)
    C64_NDX = 198,                            // keys in the buffer
    C64_RVS = 199,                            // printing reversed
    C64_LXSP = 201,                           // 201-202: where input started (row, column)
    C64_BLNSW = 204,                          // 0: the cursor flashes
    C64_PNT = 209,                            // 209-210: the cursor's logical line
    C64_PNTR = 211,                           // the cursor's column in it (0-79)
    C64_QTSW = 212,                           // quote mode
    C64_LNMX = 213,                           // the logical line's last column (39, 79)
    C64_TBLX = 214,                           // the cursor's row (0-24)
    C64_INSRT = 216,                          // characters still to insert
    C64_LDTB1 = 217,                          // 217-241: each row's line link
    C64_USER = 243,                           // 243-244: the colour of the logical line
    C64_KEYD = 631,                           // 631-640: the key buffer
    C64_COLOR = 646,                          // the colour printing uses
    C64_HIBASE = 648,                         // the screen's page (4: $0400)
    C64_XMAX = 649,                           // the key buffer's size (10)
    C64_SHFLAG = 653,                         // the shift keys held
    C64_MODE = 657,                           // 128: Shift+C= doesn't switch sets
};

#define C64_SCREEN 0x0400
#define C64_COLOUR_RAM 0xD800

/* ------------------------------------------------------------------------
 * Memory (memory.c)
 * --------------------------------------------------------------------- */

void c64_init(void);                      // power on: memory, chips, screen
// RUN/STOP+RESTORE: the chips as at power on, the screen cleared (memory
// and the program kept).
void c64_warm_start(void);
int c64_peek(unsigned int addr);          // as the processor sees it
void c64_poke(unsigned int addr, int value);
int c64_ram(unsigned int addr);           // RAM itself
void c64_set_ram(unsigned int addr, int value);
int c64_colour(int offset);               // colour RAM (0-1023), 0-15
void c64_set_colour(int offset, int value);
// The character "ROM": 4KB, as at $D000 (two sets, each 256 characters:
// the 128 drawn, then the same reversed).
int c64_char_rom(int offset);
int c64_vic_bank(void);                   // the 16KB the VIC sees (CIA 2)

/* ------------------------------------------------------------------------
 * The VIC-II (vic.c): registers at $D000-$D02E, repeated to $D3FF
 * --------------------------------------------------------------------- */

void vic_init(void);
int vic_read(int reg);
void vic_write(int reg, int value);
void vic_mem_written(unsigned int addr);  // memory.c: RAM it may show changed
void vic_colour_written(int offset);      // memory.c: colour RAM changed
void vic_bank_changed(void);              // the 16KB bank (CIA 2) changed
// Bring the picture up to date with memory (now: not waiting for the
// next frame).
void vic_update(int now);
// The cursor: shown at screen offset off (0-999) or not (-1).
void vic_cursor(int off);

/* ------------------------------------------------------------------------
 * The SID (sid.c): registers at $D400-$D41C, repeated to $D7FF; played
 * on the PC speaker
 * --------------------------------------------------------------------- */

void sid_init(void);
int sid_read(int reg);
void sid_write(int reg, int value);
void sid_tick(void);                      // time passing: envelopes, the speaker

/* ------------------------------------------------------------------------
 * The screen editor (screen.c)
 * --------------------------------------------------------------------- */

void screen_init(void);                   // cleared, the cursor home
void c64_chrout(int c);                   // print a PETSCII character
void c64_print(const char *s);
// Read a line as the editor does: the cursor flashes, keys are typed
// onto the screen and edited there, and Return reads the logical line
// it's on (from where input started, if that's this line). PETSCII, up
// to cap - 1 characters; returns its length, or -1 if RESTORE was pressed.
int c64_input_line(char *buf, int cap);
void c64_show_cursor(int on);             // the flashing cursor, as for GET (204)
void c64_set_cursor(int row, int col);    // as PLOT does
int c64_column(void);                     // PNTR: 0-79
int c64_screen_code(int petscii);         // what a character is on the screen
int c64_petscii(int screen_code);         // ... and back

/* ------------------------------------------------------------------------
 * The keyboard and the clock (keys.c)
 * --------------------------------------------------------------------- */

void keys_init(void);
// Time passing: the clock, keys typed into the buffer, the picture.
// Call often (BASIC does between statements).
void c64_tick(void);
int c64_get_key(void);                    // from the buffer: PETSCII, or -1
int c64_wait_key(void);                   // ... waiting for one (-2: RESTORE)
int c64_stop_pressed(void);               // RUN/STOP (Esc) was pressed: taken
int c64_restore_pressed(void);            // RUN/STOP+RESTORE (Page Up): taken
unsigned long c64_jiffies(void);

extern const unsigned char c64_chars[2][128][8];

#endif
