def glyph_rows(ch):
    """The 8 bytes of a glyph; bit 7 is the leftmost pixel."""
    rows = [0] * 8
    for r, pattern in enumerate(GLYPHS[ch].split('/') if GLYPHS[ch] else []):
        for c, px in enumerate(pattern):
            if px == '#':
                rows[r + 1] |= 0x80 >> (c + 1)   # drawings start at column 1
    return rows


# 127 is a copyright sign, as on the Spectrum (just the symbol: programs
# use it for their own notices).
COPYRIGHT = '.####./#....#/#.##.#/#.#..#/#.##.#/#....#/.####.'


def font_table():
    """Rows for codes 32-127, laid out as the Spectrum's character set
    (96 is a pound sign and 127 a copyright sign)."""
    table = {}
    for code in range(32, 127):
        table[code] = glyph_rows(chr(code))
    GLYPHS['\x7f'] = COPYRIGHT
    table[127] = glyph_rows('\x7f')
    del GLYPHS['\x7f']
    return table


def main():
    assert len(GLYPHS) == 95, len(GLYPHS)
    for ch, art in GLYPHS.items():
        rows = art.split('/') if art else []
        assert len(rows) <= 7 and all(len(r) <= 6 for r in rows), ch
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'kernel', 'font.c')
    lines = ['/* Generated by tools/mkfont.py - edit the glyphs there. */',
             '#include "screen.h"', '',
             '// Characters 32-127, 8 bytes each (top row first, bit 7 = left).',
             'const unsigned char font[96][8] = {']
    for code, rows in font_table().items():
        name = {92: 'backslash', 96: 'pound', 127: 'copyright'}.get(code, chr(code))
        lines.append('    { %s },  // %s' % (', '.join('0x%02X' % b for b in rows), name))
    lines.append('};')
    with open(out, 'w') as f:
        f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
    main()
